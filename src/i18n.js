const ATTR = ["placeholder", "title", "aria-label", "alt"];
const IT_WORDS = /\b(di|il|la|lo|le|gli|un|una|che|per|non|è|con|del|della|dei|nel|nella|sono|hai|ti|tuo|tua|tuoi|più|già|ancora|quando|come|puoi|titolo|serie|episodio|video|guarda|vedi|segna|apri)\b/i;
const MISS = new Set();
export const missingStrings = () => [...MISS].sort();
const cache = new Map();

export function tr(s) {
  if (typeof s !== "string" || s.length < 2 || getLang() !== "en") return s;
  const lead = s.match(/^\s*/)[0], trail = s.match(/\s*$/)[0];
  const core = s.trim().replace(/\s+/g, " ");
  if (!/[A-Za-zÀ-ÿ]/.test(core)) return s;
  let r = cache.get(core);
  if (r === undefined) {
    r = D.get(core);
    if (r === undefined) for (const [re, f] of P) { if (re.test(core)) { r = core.replace(re, f); break; } }
    if (r !== undefined) cache.set(core, r);
  }
  if (r === undefined) { if (IT_WORDS.test(core) && MISS.size < 400) MISS.add(core); return s; }
  return lead + r + trail;
}

// unisce i pezzi di testo/numeri vicini ("3", " di ", "10") e traduce la frase intera
function trChildren(ch) {
  if (typeof ch === "string") return tr(ch);
  if (!Array.isArray(ch)) return ch;
  let changed = false;
  const out = [];
  let run = [];
  const flush = () => {
    if (!run.length) return;
    const text = run.filter((x) => typeof x === "string" || typeof x === "number").join("");
    const t = tr(text);
    if (run.length > 1 && t !== text) { out.push(t); changed = true; }
    else for (const x of run) { const y = typeof x === "string" ? tr(x) : x; if (y !== x) changed = true; out.push(y); }
    run = [];
  };
  for (const x of ch) {
    if (typeof x === "string" || typeof x === "number" || x == null || typeof x === "boolean") run.push(x);
    else { flush(); out.push(x); }
  }
  flush();
  return changed ? out : ch;
}

export function trProps(type, props) {
  if (!props || getLang() !== "en") return props;
  let out = props;
  if (props.children !== undefined) {
    const nc = trChildren(props.children);
    if (nc !== props.children) out = { ...props, children: nc };
  }
  if (typeof type === "string") {
    for (const k of ATTR) {
      const v = props[k];
      if (typeof v === "string") { const nv = tr(v); if (nv !== v) { if (out === props) out = { ...props }; out[k] = nv; } }
    }
  }
  return out;
}
